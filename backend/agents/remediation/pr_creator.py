"""PRCreator node (prompt 06): branch → commit → push → pull request.

Runs only after the reviewer approved AND the Docker tester verified the
patch. It opens a PR only when ALL of these hold:
  1. the user explicitly asked for it (create_pr on the scan, or
     open_pr on POST /api/remediate) — never implied;
  2. the server allows it (PR_CREATION_ENABLED=true) with a GITHUB_TOKEN
     and the repository listed in PR_ALLOWED_REPOS;
  3. the scanned revision is still the base branch head.
Every path records a structured `pr` outcome
(created | exists | dry_run | skipped | blocked | failed) with a reason;
a PR counts as created only when the GitHub API returned it.
"""

from __future__ import annotations

import json
import logging
import os
import threading
import time

logger = logging.getLogger(__name__)


def _requested(state: dict) -> bool:
    if "open_pr" in state:
        return bool(state.get("open_pr"))
    return bool(state.get("create_pr"))


def _cwe_hint(target: dict) -> str:
    text = f"{target.get('category', '')} {target.get('description', '')}"
    import re
    match = re.search(r"CWE-\d+", text, re.IGNORECASE)
    return match.group(0).lower() if match else (target.get("id") or "fix")


def build_pr_body(state: dict) -> tuple[str, str]:
    """(title, markdown body) from recorded evidence only."""
    target = state.get("target_vuln") or {}
    patch = state.get("code_patch") or {}
    review = state.get("review") or {}
    tests = state.get("test_reports") or {}
    base, before, after = (tests.get("baseline") or {},
                           tests.get("exploit_before") or {},
                           tests.get("after") or {})
    desc = (target.get("description") or target.get("category") or "security issue").strip()
    short = desc if len(desc) <= 60 else desc[:57] + "…"
    title = f"fix(security): {short}"
    checks = "\n".join(
        f"- [{'x' if c.get('passed') else ' '}] {c.get('name')}: {c.get('detail')}"
        for c in review.get("checks", []))
    diff = (patch.get("diff") or "")[:20000]
    body = f"""## Security fix: {desc}

**Severity:** {target.get('severity', '?')} · **Category:** {target.get('category', '?')} · **Location:** `{target.get('file', '?')}:{target.get('line', '?')}`

### What changed
{patch.get('rationale', '(no rationale recorded)')}

Files: {', '.join(f'`{f}`' for f in patch.get('files_changed', []))} · exploit test: `{patch.get('test_file', '')}`

<details><summary>Diff</summary>

```diff
{diff}
```
</details>

### Verification evidence (Docker sandbox, network disabled)
| Phase | Result |
|---|---|
| Baseline suite on original code | {base.get('passed', 0)}/{base.get('total', 0)} passed |
| Exploit test on original code | {before.get('failed', 0) + before.get('errors', 0)} failing — vulnerability reproduced |
| Full suite on patched code | {after.get('passed', 0)}/{after.get('total', 0)} passed, 0 regressions |

### Reviewer gate (approved)
{checks or '- (no checks recorded)'}

LLM review: {(review.get('llm') or {}).get('summary', '')}

### Caveats
- Generated by an automated pipeline (scan `{state.get('scan_id')}`, attempt {state.get('attempts', 0)}). Verification covers the repository's own test suite plus one generated exploit test; it is not a proof of complete remediation.
- Please review the change before merging.
"""
    return title, body


_LOCKS: dict[str, threading.Lock] = {}
_LOCKS_GUARD = threading.Lock()


def _branch_lock(branch: str) -> threading.Lock:
    with _LOCKS_GUARD:
        return _LOCKS.setdefault(branch, threading.Lock())


def _require_branch_matches(api, slug: str, branch: str, work_dir: str,
                            files: list[str]) -> None:
    """Refuse to open a PR from an existing branch unless every file we
    would commit is byte-identical there to the Docker-verified copy.
    A same-named branch with other content is not our verified patch."""
    from tools import github_pr as gh
    for rel in files:
        with open(os.path.join(work_dir, rel), "rb") as fh:
            ours = fh.read()
        theirs = api.file_at(slug, rel, branch)
        if theirs is None or theirs.replace(b"\r\n", b"\n") != ours.replace(b"\r\n", b"\n"):
            raise gh.PRBlocked(f"Branch {branch} already exists on GitHub but its "
                               f"{rel} differs from the verified patch; refusing "
                               "to open a PR from it.")


def _evidence_gap(tests: dict) -> str:
    """Re-derive 'verified' from the raw phases (defence in depth)."""
    before, after = tests.get("exploit_before") or {}, tests.get("after") or {}
    for name, rep in (("exploit_before", before), ("after", after)):
        if not rep:
            return f"{name} phase missing"
        if rep.get("infra_error") or rep.get("timed_out"):
            return f"{name} phase did not run cleanly"
    if (before.get("failed") or 0) < 1:
        return "exploit did not reproduce on the original code"
    if (after.get("failed") or 0) or (after.get("errors") or 0):
        return "patched suite has failures or errors"
    return ""


def _result(status: str, reason: str = "", **extra) -> dict:
    return {"requested": extra.pop("requested", True), "status": status,
            "reason": reason, "url": extra.pop("url", None),
            "number": extra.pop("number", None),
            "branch": extra.pop("branch", None), "base": extra.pop("base", None),
            "commit": extra.pop("commit", None), "at": time.time(), **extra}


def pr_creator_node(state: dict) -> dict:
    from tools import github_pr as gh
    from tools.run_artifacts import save_text

    scan_id = state.get("scan_id", "unknown")
    logs: list[str] = []

    def done(pr: dict) -> dict:
        save_text(scan_id, "pr_result.json", json.dumps(pr, indent=2, default=str))
        verified = state.get("test_verdict") == "verified"
        status = ("pr_opened" if pr["status"] in (gh.CREATED, gh.EXISTS)
                  else "verified_no_pr" if verified else "failed")
        logs.append(f"[PRCreator] {pr['status'].upper()}"
                    + (f": {pr['reason']}" if pr.get("reason") else "")
                    + (f" → {pr['url']}" if pr.get("url") else ""))
        return {"pr": pr, "pr_url": pr.get("url"), "remediation_status": status,
                "agent_logs": logs}

    if not _requested(state):
        return done(_result(gh.SKIPPED, "PR creation was not requested for "
                            "this run.", requested=False))
    # Deterministic gate, independent of graph routing.
    if state.get("test_verdict") != "verified" or \
            not (state.get("review") or {}).get("approved"):
        return done(_result(gh.BLOCKED, "The patch is not reviewer-approved "
                            "and Docker-verified; no PR is opened."))
    evidence_gap = _evidence_gap(state.get("test_reports") or {})
    if evidence_gap:
        return done(_result(gh.BLOCKED, f"Test evidence is inconclusive "
                            f"({evidence_gap}); no PR is opened."))

    cfg = gh.pr_config()
    try:
        slug = gh.parse_repo_slug(state.get("repo_url", ""))
    except gh.PRBlocked as exc:
        return done(_result(gh.BLOCKED, str(exc)))
    reason = cfg.missing(slug)
    if reason:
        return done(_result(gh.SKIPPED, reason))

    patch = state.get("code_patch") or {}
    work_dir = state.get("work_dir", "")
    repo_path = state.get("repo_path", "")
    test_rel = patch.get("test_file", "")
    files = list(dict.fromkeys([*patch.get("files_changed", []), test_rel]))
    files = [f for f in files if f]
    try:
        with open(os.path.join(work_dir, test_rel), encoding="utf-8",
                  errors="replace") as fh:
            test_content = fh.read()
    except OSError:
        return done(_result(gh.FAILED, "The verified work copy is gone; "
                            "cannot commit the patch."))

    fingerprint = gh.patch_fingerprint(patch.get("diff", ""), test_content)
    try:
        branch = gh.branch_name(cfg.branch_prefix, scan_id,
                                _cwe_hint(state.get("target_vuln") or {}),
                                fingerprint)
    except gh.PRBlocked as exc:
        return done(_result(gh.BLOCKED, str(exc)))
    title, body = build_pr_body(state)
    save_text(scan_id, "pr_body.md", f"# {title}\n\n{body}")

    if cfg.dry_run:
        return done(_result(gh.DRY_RUN, "DRY_RUN_PR=true: PR body written to "
                            "pr_body.md; nothing pushed.", branch=branch))

    api = gh.GitHub(cfg.token)
    try:
        repo = api.repo(slug)
        if repo.get("full_name", "").lower() != slug.lower():
            raise gh.PRBlocked(f"Repository identity mismatch "
                               f"({repo.get('full_name')} != {slug}).")
        if not (repo.get("permissions") or {}).get("push"):
            raise gh.PRBlocked(f"The token has no push permission on {slug}.")
        base = cfg.base_branch or repo.get("default_branch") or "main"
        base_sha = api.branch_sha(slug, base)
        if base_sha is None:
            raise gh.PRBlocked(f"Base branch '{base}' does not exist on {slug}.")
        if gh.local_head(repo_path) != base_sha:
            raise gh.PRBlocked(f"'{base}' moved since this scan; the patch was "
                               "verified against older code. Re-scan first.")
        owner = slug.split("/")[0]

        # Serialise per branch: two runs that verified the same patch must
        # not race to push / open it twice in this process. Across
        # processes the remote checks below (existing PR, branch content,
        # create-then-recheck) give the same guarantee.
        with _branch_lock(branch):
            def existing_pr():
                pr_ = api.open_pr_for(slug, owner, branch)
                if pr_:
                    logger.info("PR for %s already open: %s", branch, pr_["html_url"])
                    return done(_result(gh.EXISTS, "This exact patch already has an "
                                        "open pull request (not duplicated).",
                                        url=pr_["html_url"], number=pr_["number"],
                                        branch=branch, base=base))
                return None

            found = existing_pr()
            if found:
                return found

            commit = None
            if api.branch_sha(slug, branch) is None:
                try:
                    commit = gh.commit_and_push(
                        repo_path=repo_path, work_dir=work_dir, files=files,
                        branch=branch, cfg=cfg,
                        message=f"{title}\n\nAutomated by PatchPilot "
                                f"scan {scan_id}. Verified in a Docker sandbox.")
                    logs.append(f"[PRCreator] Pushed {branch} ({commit[:10]})")
                except gh.PRBlocked:
                    raise
                except Exception:
                    # A concurrent pusher may have won the race; only reuse
                    # its branch if it holds exactly the verified files.
                    if api.branch_sha(slug, branch) is None:
                        raise
                    _require_branch_matches(api, slug, branch, work_dir, files)
                    logs.append(f"[PRCreator] {branch} was pushed concurrently "
                                "with identical content — reusing it")
            else:
                _require_branch_matches(api, slug, branch, work_dir, files)
                logs.append(f"[PRCreator] Branch {branch} already pushed with "
                            "the verified content (retry) — reusing it")
            try:
                pr = api.create_pr(slug, title=title, head=branch, base=base, body=body)
            except gh.GitHubRateLimited:
                raise
            except Exception:
                # The PR may exist anyway (lost response, concurrent create,
                # 422 "already exists"): report it rather than retry blindly.
                found = existing_pr()
                if found:
                    return found
                raise
            logger.info("PR created for scan %s: %s", scan_id, pr["html_url"])
            return done(_result(gh.CREATED, "", url=pr["html_url"],
                                number=pr["number"], branch=branch, base=base,
                                commit=commit))
    except gh.PRBlocked as exc:
        return done(_result(gh.BLOCKED, str(exc), branch=branch))
    except gh.GitHubRateLimited as exc:
        logger.warning("PR creation rate limited for scan %s: %s", scan_id, exc)
        return done(_result(gh.FAILED, str(exc), branch=branch, retryable=True))
    except Exception as exc:  # network/API/git failure: record, never crash
        message = api.mask(str(exc))
        logger.error("PR creation failed for scan %s: %s", scan_id, message)
        return done(_result(gh.FAILED, message, branch=branch))
